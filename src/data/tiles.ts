import type { BoardTile, MinigameId, SpinnerSegment } from '../types/game';
import { alcoholFreeCopy } from '../utils/text';

type TileInput = Omit<BoardTile, 'alcoholFreeText'> & {
  alcoholFreeText?: BoardTile['alcoholFreeText'];
};

function makeTile(tile: TileInput): BoardTile {
  const { alcoholFreeText, ...baseTile } = tile;
  return {
    ...baseTile,
    alcoholFreeText: alcoholFreeText ?? {
      title: alcoholFreeCopy(tile.title),
      description: alcoholFreeCopy(tile.description),
    },
  };
}

