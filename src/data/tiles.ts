type TileInput = Omit<BoardTile, 'alcoholFreeText'>;

function makeTile(tile: TileInput): BoardTile {
  return {
    ...tile,
    alcoholFreeText: {
      title: alcoholFreeCopy(tile.title),
      description: alcoholFreeCopy(tile.description),
    },
  };
}

